  <h1>❓ Ayuda</h1>

  <h2>BS-OS · v1.0</h2>
  <p>
    Bienvenido a BS-OS, el escritorio de Bladimir Salazar. Este es un sitio web
    estilo Windows 3.1 que reúne todos mis proyectos en un solo lugar.
  </p>

  <h2>Cómo usar</h2>
  <ul>
    <li><strong>Doble clic</strong> en un ícono del escritorio para abrir una app.</li>
    <li><strong>Clic</strong> en una ventana para traerla al frente.</li>
    <li>Arrastra la <strong>barra de título</strong> para mover una ventana.</li>
    <li>Arrastra la <strong>esquina inferior derecha</strong> para redimensionar.</li>
    <li>Usa los botones de la ventana: <strong>minimizar</strong> [_], <strong>maximizar</strong> [▢], <strong>cerrar</strong> [✕].</li>
    <li>El botón <strong>Inicio</strong> abre el menú de programas.</li>
    <li>La <strong>barra de tareas</strong> muestra las ventanas abiertas y el reloj.</li>
  </ul>

  <h2>Atajos de teclado</h2>
  <ul>
    <li><code>Esc</code> — Cerrar menú inicio / diálogos</li>
    <li><code>Konami Code</code> (↑↑↓↓←→←→ B A) — Desbloquear Galaga</li>
    <li>Triple clic en la esquina superior izquierda — Easter egg (BSoD)</li>
  </ul>

